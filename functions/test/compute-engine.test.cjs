"use strict";
const{describe,it}=require("node:test");
const assert=require("node:assert/strict");
const{existsSync}=require("node:fs");
const{resolve}=require("node:path");
const modulePath=resolve(__dirname,"../private-engine.cjs");
describe("Private server engine binary contract",()=>{
 it("must be generated by the secure backend build step",()=>{
  assert.ok(existsSync(modulePath),"Run npm run build:private-engine before this test");
 });
 it("executes a bounded 2-qubit Bell sample without browser worker code",()=>{
  if(!existsSync(modulePath))return;
  const engine=require(modulePath);
  const source="OPENQASM 2.0; qreg q[2]; creg c[2]; h q[0]; cx q[0],q[1];";
  const prepared=engine.prepareIndustryJob({
   schema:"MAH-Quantum-Industry-Job/v1",jobId:"d25-protected-bell",kind:"circuit",
   operation:"execute",source,shots:64,seed:25
  });
  const out=engine.executePreparedIndustryJob(prepared);
  assert.equal(out.status,"completed");
  assert.equal(out.samples.completedShots,64);
  assert.deepEqual(Object.keys(out.samples.counts).sort(),["00","11"]);
 });
});